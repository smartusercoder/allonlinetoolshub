const slugify = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

const generatedTools = [];
let templateIndex = 0;
let categoryIndex = 0;

while (baseTools.length + generatedTools.length < 520) {
  const template = templates[templateIndex % templates.length];
  const category = categories[categoryIndex % categories.length];
  const name = `${template} (${category})`;
  const id = slugify(`${template}-${category}`);

  generatedTools.push({
    id,
    name,
    category,
    type: "directory",
    description: `High-demand ${template.toLowerCase()} tailored for ${category.toLowerCase()} workflows.`,
    keywords: [template, category, "exclusive", "popular"],
  });

  templateIndex += 1;
  if (templateIndex % templates.length === 0) {
    categoryIndex += 1;
  }
}

export const tools = [...baseTools, ...generatedTools];
